/**
 * Navigation groups. Each item: [text, href, icon, page_key?]
 * page_key is used by the owner's page-access matrix.
 */
function role_nav(string $role): array
{
    $nav = [
        'owner' => [
            ['title' => 'Overview', 'items' => [
                ['Dashboard', 'dashboard', 'home', 'dashboard'],
            ]],
            ['title' => 'Laundry', 'items' => [
                ['Orders', 'orders', 'clipboard', 'orders'],
                ['Customers', 'customers', 'users', 'customers'],
                ['Services & Pricing', 'services', 'tag', 'services'],
                ['Staff Roster', 'employees', 'user', 'employees'],
            ]],
            ['title' => 'Inventory', 'items' => [
                ['Inventory', 'inventory', 'layers', 'inventory'],
                ['Inventory Config', 'inventory-settings', 'settings', 'inventory_settings'],
            ]],
            ['title' => 'Insights', 'items' => [
                ['Reports', 'reports', 'chart', 'reports'],
                ['Audit Logs', 'logs', 'clock', 'logs'],
            ]],
            ['title' => 'System', 'items' => [
                ['Accounts', 'accounts', 'shield', 'accounts'],
                ['System Settings', 'system-settings', 'settings', 'system_settings'],
            ]],
        ],
        'staff' => [
            ['title' => 'Overview', 'items' => [
                ['Dashboard', 'dashboard', 'home', 'dashboard'],
            ]],
            ['title' => 'Laundry', 'items' => [
                ['Orders', 'orders', 'clipboard', 'orders'],
                ['Customers', 'customers', 'users', 'customers'],
            ]],
            ['title' => 'Inventory', 'items' => [
                ['Inventory', 'inventory', 'layers', 'inventory'],
            ]],
        ],
    ];

    // Apply owner-controlled page access filter (only for controlled roles).
    $acc = $_SESSION['user']['page_access'] ?? null;
    if ($acc !== null && in_array($role, ['owner', 'staff'], true)) {
        foreach ($nav[$role] as &$group) {
            if (!isset($group['items'])) {
                continue;
            }
            $group['items'] = array_values(array_filter($group['items'], function ($item) use ($acc) {
                return !isset($item[3]) || in_array($item[3], $acc, true);
            }));
        }
        unset($group);
        $nav[$role] = array_values(array_filter($nav[$role], function ($g) {
            return !empty($g['items']);
        }));
    }

    return $nav[$role] ?? [];
}
